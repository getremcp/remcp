// Explicit owner-private unsigned macOS/Linux QA bundle admission.
// Never execute a remotely supplied binary or trust only the executable hash:
// PyInstaller onedir loads many adjacent native modules and shared libraries.
import {createHash} from 'node:crypto';
import {lstatSync,realpathSync,readdirSync,readFileSync,readlinkSync,
        openSync,readSync,closeSync} from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';

const SHA=/^[a-f0-9]{64}$/;
const COMMIT=/^[a-f0-9]{40}$/;
// The distro's bundled GStreamer runtime can exceed 500 MiB on Linux.
// Still cap each owner-private QA bundle and verify every regular file.
const MAX_MANIFEST=256*1024,MAX_FILES=3500,MAX_BYTES=1024*1024*1024;
const ALLOWED={darwin:{arch:'arm64',platform:'macos-arm64'},
  linux:{arch:'x64',platform:'linux-x64'}};

function inside(root,filename){
  const relative=path.relative(root,filename);
  return relative!==''&&!relative.startsWith('..'+path.sep)&&
    relative!=='..'&&!path.isAbsolute(relative);
}
function ownedPrivate(filename,{file=false}={}){
  const info=lstatSync(filename);
  if(info.isSymbolicLink()||info.uid!==process.getuid?.()||
     (info.mode&0o022)!==0||
     (file?(!info.isFile()||info.nlink!==1):!info.isDirectory()))
    throw Error('Untrusted local WebRTC QA path');
  return info;
}
function securePath(base,filename,{file=false}={}){
  if(!path.isAbsolute(filename)||!inside(base,filename))throw Error('Outside owner QA directory');
  let cursor=path.dirname(filename);
  while(cursor!==base){
    ownedPrivate(cursor);
    cursor=path.dirname(cursor);
  }
  ownedPrivate(base);
  return ownedPrivate(filename,{file});
}
function digest(filename){
  const hash=createHash('sha256');
  const buffer=Buffer.allocUnsafe(1024*1024);
  const fd=openSync(filename,'r');
  try{
    let size;
    while((size=readSync(fd,buffer,0,buffer.length,null))>0){
      hash.update(buffer.subarray(0,size));
    }
  }finally{closeSync(fd);}
  return hash.digest('hex');
}
function validRelative(value){
  return typeof value==='string'&&value.length>0&&value.length<=4096&&
    !path.posix.isAbsolute(value)&&
    value.split('/').every(part=>part!==''&&part!=='.'&&part!=='..')&&
    !value.includes('\\')&&!value.includes('\0');
}
function walk(root){
  const entries=[];
  const visit=(dir,prefix)=>{
    for(const name of readdirSync(dir).sort()){
      const rel=prefix?prefix+'/'+name:name;
      if(!validRelative(rel))throw Error('Invalid onedir item');
      const absolute=path.join(dir,name);
      const info=lstatSync(absolute);
      const type=info.isSymbolicLink()?'symlink':
        info.isFile()?'file':info.isDirectory()?'dir':'unsafe';
      if(type==='unsafe')throw Error('Unsafe onedir item');
      entries.push({rel,absolute,info,type});
      if(entries.length>MAX_FILES)throw Error('Too many onedir items');
      if(type==='dir')visit(absolute,rel);
    }
  };
  visit(root,'');
  return entries;
}
export function posixFrozenQaTrusted(filename,{
  env=process.env,platform=process.platform,architecture=process.arch,
  home=os.homedir(),uid=process.getuid?.(),
}={}){
  if(platform!==process.platform||!ALLOWED[platform]||
     ALLOWED[platform].arch!==architecture||uid!==process.getuid?.()||
     env.REMCP_WEBRTC_RUNTIME_PILOT!=='1'||
     env.REMCP_WEBRTC_FROZEN_QA_MODE!=='1'||
     env.REMCP_WEBRTC_ALLOW_UNSIGNED_FROZEN_QA!=='1'||
     !SHA.test(env.REMCP_WEBRTC_FROZEN_SHA256||'')||
     !SHA.test(env.REMCP_WEBRTC_FROZEN_MANIFEST_SHA256||'')||
     typeof filename!=='string'||!path.isAbsolute(filename)||
     typeof env.REMCP_WEBRTC_FROZEN_MANIFEST!=='string')
    return false;
  try{
    const base=path.join(realpathSync(home),'.local','share','remcp');
    const root=path.dirname(filename);
    const manifestPath=env.REMCP_WEBRTC_FROZEN_MANIFEST;
    // The executable is always <bundle>/<bundle name> as generated by
    // our PyInstaller QA; reject arbitrary script names and root replacements.
    if(path.basename(filename)!==path.basename(root)||
       !inside(base,root)||!inside(base,manifestPath))
      return false;
    securePath(base,root);
    const exe=securePath(base,filename,{file:true});
    const entry=securePath(base,manifestPath,{file:true});
    if(entry.size>MAX_MANIFEST||exe.size>MAX_BYTES)return false;
    if(digest(manifestPath)!==env.REMCP_WEBRTC_FROZEN_MANIFEST_SHA256||
       digest(filename)!==env.REMCP_WEBRTC_FROZEN_SHA256)return false;
    const manifest=JSON.parse(readFileSync(manifestPath,'utf8'));
    if(manifest.format!=='remcp-native-webrtc-qa-unsigned-v1'||
       manifest.platform!==ALLOWED[platform].platform||
       !COMMIT.test(manifest.sourceCommit||'')||
       manifest.distributionChannel!=='unsigned-owner-private-QA'||
       manifest.productionReady!==false||manifest.published!==false||
       !Array.isArray(manifest.contents)||manifest.contents.length>MAX_FILES)
      return false;
    const observed=walk(root);
    if(observed.length!==manifest.contents.length)return false;
    const expected=new Map();
    for(const item of manifest.contents){
      if(!validRelative(item.path)||!['dir','file','symlink'].includes(item.type)||
         expected.has(item.path))return false;
      expected.set(item.path,item);
    }
    let total=0;
    for(const {rel,absolute,info,type} of observed){
      const item=expected.get(rel);
      // POSIX symlink modes are normally 0777 and have no security effect;
      // only the owner-private parent and resolved in-tree target matter.
      if(!item||item.type!==type||info.uid!==uid||
         (type!=='symlink'&&(info.mode&0o022)!==0))return false;
      if(type==='file'){
        if(info.nlink!==1||info.size!==item.bytes||
           !SHA.test(item.sha256||'')||digest(absolute)!==item.sha256)
          return false;
        total+=info.size;
        if(total>MAX_BYTES)return false;
      }else if(type==='symlink'){
        if(typeof item.target!=='string'||!item.target||
           path.isAbsolute(item.target)||item.target!==readlinkSync(absolute))
          return false;
        const resolved=realpathSync(absolute);
        if(!inside(root,resolved))return false;
      }
    }
    return total===manifest.totalRegularBytes;
  }catch{return false;}
}
