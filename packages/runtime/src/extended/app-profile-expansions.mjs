// Curated, non-exhaustive cross-platform application discovery profiles.
// A missing launch target means unsupported; it is never a request to install.
// UI routes are advertised only for keys whose default semantics are known.
const profile=(id,category,name,win,mac,linux,processes={},routes={},aliases=[])=>{
  const targets=Object.fromEntries([['win32',win],['darwin',mac],['linux',linux]].filter(([,v])=>v));
  const defaults=Object.fromEntries(Object.entries(targets).map(([os,target])=>[
    os,[target.split(/[\\/]/).at(-1).replace(/\\.exe$/i,'')],
  ]));
  const moduleName={'libreoffice-impress':'--impress','libreoffice-draw':'--draw','libreoffice-base':'--base'}[id];
  const launchArgs=moduleName?{linux:[moduleName],darwin:[moduleName]}:{};
  const moduleProcesses=moduleName?{
    win32:['soffice','soffice.bin'],darwin:['LibreOffice'],
    linux:['soffice','soffice.bin','libreoffice'],
  }:{};
  return {id,category,aliases:[name,...aliases],targets,
    processes:{...defaults,...moduleProcesses,...processes},routes,launchArgs};
};
